# 8. EXTRACT REFERENCE RANGES
# ------------------------------------------------------------
def add_reference_ranges(text, results):

    # Look for ranges such as:
    # 12-16
    # 4.0-11.0
    # 150-450

    range_pattern = (
        r"(\d+(?:\.\d+)?)"
        r"\s*-\s*"
        r"(\d+(?:\.\d+)?)"
    )

    ranges = re.findall(
        range_pattern,
        text
    )

    # NOTE:
    # Ranges are only added if detected.
    # They are not blindly assigned to parameters
    # because CBC reports have different layouts.

    if ranges:

        for parameter in results:

            results[parameter]["reference_range"] = None

    else:

        for parameter in results:

            results[parameter]["reference_range"] = None

    return results


