# 7. EXTRACT CBC PARAMETERS
# ------------------------------------------------------------
def extract_cbc_data(text):

    results = {}

    # Normalize OCR text
    text = text.replace("—", "-")
    text = text.replace("–", "-")
    text = text.replace("|", " ")

    # --------------------------------------------------------
    # Parameter patterns
    # --------------------------------------------------------
    parameters = {

        "hemoglobin": [
            r"(?:hemoglobin|haemoglobin|h[a-z]?b)"
            r"\s*[:\-]?\s*"
            r"([\d]+(?:\.\d+)?)"
            r"\s*([a-zA-Z/%µμ]*)"
        ],

        "rbc": [
            r"(?:rbc|red\s*blood\s*cells?)"
            r"\s*[:\-]?\s*"
            r"([\d]+(?:\.\d+)?)"
            r"\s*([a-zA-Z/%µμ]*)"
        ],

        "wbc": [
            r"(?:wbc|white\s*blood\s*cells?)"
            r"\s*[:\-]?\s*"
            r"([\d]+(?:\.\d+)?)"
            r"\s*([a-zA-Z/%µμ]*)"
        ],

        "platelets": [
            r"(?:platelets?|plt)"
            r"\s*[:\-]?\s*"
            r"([\d]+(?:\.\d+)?)"
            r"\s*([a-zA-Z/%µμ]*)"
        ],

        "hematocrit": [
            r"(?:hematocrit|haematocrit|hct|pcv)"
            r"\s*[:\-]?\s*"
            r"([\d]+(?:\.\d+)?)"
            r"\s*([a-zA-Z/%µμ]*)"
        ],

        "mcv": [
            r"\bmcv\b"
            r"\s*[:\-]?\s*"
            r"([\d]+(?:\.\d+)?)"
            r"\s*([a-zA-Z/%µμ]*)"
        ],

        "mch": [
            r"\bmch\b"
            r"\s*[:\-]?\s*"
            r"([\d]+(?:\.\d+)?)"
            r"\s*([a-zA-Z/%µμ]*)"
        ],

        "mchc": [
            r"\bmchc\b"
            r"\s*[:\-]?\s*"
            r"([\d]+(?:\.\d+)?)"
            r"\s*([a-zA-Z/%µμ]*)"
        ],

        "rdw": [
            r"(?:rdw|red\s*cell\s*distribution\s*width)"
            r"\s*[:\-]?\s*"
            r"([\d]+(?:\.\d+)?)"
            r"\s*([a-zA-Z/%µμ]*)"
        ],

        "neutrophils": [
            r"(?:neutrophils?|neutrophil)"
            r"\s*[:\-]?\s*"
            r"([\d]+(?:\.\d+)?)"
            r"\s*([a-zA-Z/%µμ]*)"
        ],

        "lymphocytes": [
            r"(?:lymphocytes?|lymphocyte)"
            r"\s*[:\-]?\s*"
            r"([\d]+(?:\.\d+)?)"
            r"\s*([a-zA-Z/%µμ]*)"
        ],

        "monocytes": [
            r"(?:monocytes?|monocyte)"
            r"\s*[:\-]?\s*"
            r"([\d]+(?:\.\d+)?)"
            r"\s*([a-zA-Z/%µμ]*)"
        ],

        "eosinophils": [
            r"(?:eosinophils?|eosinophil)"
            r"\s*[:\-]?\s*"
            r"([\d]+(?:\.\d+)?)"
            r"\s*([a-zA-Z/%µμ]*)"
        ],

        "basophils": [
            r"(?:basophils?|basophil)"
            r"\s*[:\-]?\s*"
            r"([\d]+(?:\.\d+)?)"
            r"\s*([a-zA-Z/%µμ]*)"
        ]
    }

    # --------------------------------------------------------
    # Search for each parameter
    # --------------------------------------------------------
    for parameter, patterns in parameters.items():

        for pattern in patterns:

            match = re.search(
                pattern,
                text,
                re.IGNORECASE
            )

            if match:

                value = match.group(1)
                unit = match.group(2).strip()

                # Convert numeric value
                try:

                    value = float(value)

                    if value.is_integer():
                        value = int(value)

                except:

                    pass

                results[parameter] = {
                    "value": value,
                    "unit": unit if unit else None
                }

                break

    return results


