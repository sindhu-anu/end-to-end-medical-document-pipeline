import pandas as pd

df = pd.read_csv("/content/medical_dataset_with_images.csv")

print(df.shape)

df.head()

import torch

from transformers import AutoTokenizer
from transformers import AutoModelForSeq2SeqLM

MODEL_NAME = "facebook/nllb-200-distilled-600M"

tokenizer = AutoTokenizer.from_pretrained(MODEL_NAME)

model = AutoModelForSeq2SeqLM.from_pretrained(MODEL_NAME)

device = "cuda" if torch.cuda.is_available() else "cpu"

model.to(device)

print(device)

def translate(text):

    tokenizer.src_lang = "eng_Latn"

    encoded = tokenizer(
        text,
        return_tensors="pt",
        truncation=True,
        max_length=512
    )

    encoded = {k: v.to(device) for k, v in encoded.items()}

    generated = model.generate(
        **encoded,
        forced_bos_token_id=tokenizer.convert_tokens_to_ids("hin_Deva"),
        max_new_tokens=512,
        num_beams=5
    )

    return tokenizer.batch_decode(
        generated,
        skip_special_tokens=True
    )[0]

from tqdm import tqdm

predictions = []

for text in tqdm(df["transcription_english"]):

    predictions.append(
        translate(str(text))
    )

df["predicted_hindi"] = predictions

df.to_csv(
    "NLLB_translation_results.csv",
    index=False
)

