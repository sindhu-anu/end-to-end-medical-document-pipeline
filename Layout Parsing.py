import os
import re
from google.colab import files
from docx import Document
from pdf2image import convert_from_path
import easyocr

# ==========================================
# Read DOCX
# ==========================================

def read_docx(filename):
    doc = Document(filename)
    text = []
    for p in doc.paragraphs:
        text.append(p.text)
    return "\n".join(text).lower()

# ==========================================
# Extract Words
# ==========================================

def get_words(text):
    words = re.findall(r'\b[a-zA-Z0-9\-]+\b', text.lower())
    words = [w for w in words if len(w) > 2]
    return list(set(words))

# ==========================================
# Accuracy
# ==========================================

def calculate_accuracy(gt_words, ocr_words):

    correct = 0
    missed = []

    for w in gt_words:
        if w in ocr_words:
            correct += 1
        else:
            missed.append(w)

    acc = correct / len(gt_words)

    return acc, correct, missed

# ==========================================
# EasyOCR
# ==========================================

print("Loading EasyOCR...")
reader = easyocr.Reader(['en'])

# ==========================================
# OCR Function
# ==========================================

def perform_ocr(upload_title):

    print("\n")
    print("="*60)
    print(upload_title)
    print("="*60)

    uploaded = files.upload()

    all_words = []

    for filename in uploaded.keys():

        ext = os.path.splitext(filename)[1].lower()

        # ---------------- PDF ----------------

        if ext == ".pdf":

            print("Reading PDF :", filename)

            pages = convert_from_path(filename)

            for i, page in enumerate(pages):

                image_name = f"page_{i}.png"
                page.save(image_name, "PNG")

                result = reader.readtext(image_name)

                for (_, text, _) in result:

                    words = re.findall(r'\b[a-zA-Z0-9\-]+\b', text.lower())

                    all_words.extend(words)

        # ---------------- IMAGE ----------------

        else:

            print("Reading Image :", filename)

            result = reader.readtext(filename)

            for (_, text, _) in result:

                words = re.findall(r'\b[a-zA-Z0-9\-]+\b', text.lower())

                all_words.extend(words)

    return list(set(all_words))

