def correct_drug_name(name):
    name = str(name).lower().strip()

    # remove noise
    name = name.replace("-", "").replace(" ", "")

    match = process.extractOne(name, DRUG_DB, scorer=fuzz.ratio)

    if match and match[1] > 70:
        return match[0]

    return name


def extract_fields(text):
    text = text.lower()

    dose_match = re.search(r'(\d+\s*ml|\d+-\d+-\d+|\d+\s*tab|\d+\s*mg)', text)
    dose = dose_match.group(1) if dose_match else ""

    if "q6h" in text:
        freq = "q6h"
    elif "tds" in text:
        freq = "tds"
    elif "bd" in text:
        freq = "bd"
    elif "od" in text:
        freq = "od"
    elif "sos" in text:
        freq = "sos"
    else:
        freq = ""

    dur_match = re.search(r'(\d+\s*(d|day|days|week|weeks))', text)
    duration = ""
    if dur_match:
        duration = dur_match.group(1).replace("days", "d").replace("day", "d")

    return dose, freq, duration


def postprocess(data):

    meds = data.get("medicines", [])
    cleaned = []
    seen = set()

    for med in meds:

        combined = " ".join([str(v) for v in med.values()]).lower()

        raw_name = med.get("name", "")
        name = correct_drug_name(raw_name)

        dose, freq, duration = extract_fields(combined)

        if not name:
            continue

        key = (name, dose, freq, duration)
        if key in seen:
            continue
        seen.add(key)

        cleaned.append({
            "name": name,
            "dose": dose,
            "frequency": freq,
            "duration": duration
        })

    return {"medicines": cleaned}

