def preprocess_image(input_path, output_path="processed.jpg"):

    img = cv2.imread(input_path)
    if img is None:
        raise ValueError(f"Image not loaded: {input_path}")

    img = cv2.resize(img, (900, 900))

    gray = cv2.cvtColor(img, cv2.COLOR_BGR2GRAY)

    # contrast
    clahe = cv2.createCLAHE(clipLimit=2.0, tileGridSize=(8,8))
    gray = clahe.apply(gray)

    # sharpen
    kernel = np.array([[0,-1,0],[-1,5,-1],[0,-1,0]], dtype=np.float32)
    gray = cv2.filter2D(gray, -1, kernel)

    # threshold
    thresh = cv2.adaptiveThreshold(
        gray, 255,
        cv2.ADAPTIVE_THRESH_MEAN_C,
        cv2.THRESH_BINARY,
        11, 2
    )

    cv2.imwrite(output_path, thresh)
    return output_path

def extract_prescription(image_path):

    image = Image.open(image_path).convert("RGB")

    messages = [
        {
            "role": "user",
            "content": [
                {"type": "image"},
                {"type": "text", "text": """
Extract medicines from this prescription.

- Try to infer medicine names if unclear
- Extract dose, frequency, duration
- Do not return empty unless nothing visible

Return JSON:
{
  "medicines": [
    {
      "name": "",
      "dose": "",
      "frequency": "",
      "duration": ""
    }
  ]
}
"""}
            ]
        }
    ]

    text = processor.apply_chat_template(
        messages, tokenize=False, add_generation_prompt=True
    )

    inputs = processor(
        text=[text],
        images=[image],
        return_tensors="pt"
    ).to(device)

    output = model.generate(**inputs, max_new_tokens=512)

    return processor.batch_decode(output, skip_special_tokens=True)[0]

def parse_json(output_text):
    try:
        if "```json" in output_text:
            match = re.search(r"```json\s*(\{.*?\})\s*```", output_text, re.DOTALL)
            if match:
                return json.loads(match.group(1))

        match = re.search(r"\{.*\}", output_text, re.DOTALL)
        if match:
            return json.loads(match.group())

        return {"medicines": []}

    except:
        return {"medicines": []}

