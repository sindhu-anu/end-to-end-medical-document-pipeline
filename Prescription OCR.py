def json_to_eval_text(data):
    lines = []

    # Patient info
    if data.get("patient_name"):
        lines.append(f"Name: {data['patient_name']}")

    if data.get("date"):
        lines.append(f"Date: {data['date']}")

    # Advice section (important)
    lines.append("Advice:")

    for med in data.get("medicines", []):
        line = ""

        if med.get("type"):
            line += med["type"] + " "

        line += med.get("name", "")

        if med.get("strength"):
            line += f" ({med['strength']})"

        if med.get("dose"):
            line += f" {med['dose']}"

        if med.get("frequency"):
            line += f" {med['frequency']}"

        if med.get("duration"):
            line += f" x {med['duration']}"

        lines.append(line.strip())

    return "\n".join(lines)

